CREATE TABLE IF NOT EXISTS public.clients (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  name text NOT NULL,
  contact_person text NULL,
  email text NULL,
  phone text NULL,
  address text NULL,
  street text NULL,
  city text NULL,
  state text NULL,
  country text NULL,
  coords text NULL,
  industry text NULL,
  ck_number text NULL,
  tax_number text NULL,
  vat_number text NULL,
  status text NOT NULL DEFAULT 'Active'::text,
  client_id text NULL,
  pickup_locations jsonb NULL DEFAULT '[]'::jsonb,
  dropoff_locations jsonb NULL DEFAULT '[]'::jsonb,
  credit_limit numeric(15, 2) NULL DEFAULT 0,
  postal_code text NULL,
  fax_number text NULL,
  vat_registered boolean NULL DEFAULT false,
  dormant_flag boolean NULL DEFAULT false,
  registration_number text NULL,
  registration_name text NULL,
  color text NULL,
  outline text NULL,
  style_url text NULL,
  coordinates text NULL,
  name2 text NULL,
  value text NULL,
  radius numeric(10, 2) NULL DEFAULT 100,
  coordinates5 text NULL,
  coordinates6 text NULL,
  created_at timestamp with time zone NULL DEFAULT now(),
  updated_at timestamp with time zone NULL DEFAULT now(),
  type text NULL DEFAULT 'warehouse'::text,
  contact_phone text NULL,
  contact_email text NULL,
  operating_hours text NULL,
  capacity text NULL,
  notes text NULL,
  facilities text[] NULL,
  commodity text NULL,
  "IsLoading" boolean NULL DEFAULT false,
  CONSTRAINT clients_pkey PRIMARY KEY (id)
) TABLESPACE pg_default;

CREATE INDEX IF NOT EXISTS clients_name_idx ON public.clients USING btree (name) TABLESPACE pg_default;
